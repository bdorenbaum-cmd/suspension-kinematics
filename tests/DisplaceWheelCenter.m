        function verify_at_ride_height(testCase)
            params = struct( ...
                "UCO",  testCase.P.FUCO, ...
                "UCF",  testCase.P.FUCF, ...
                "UCA",  testCase.P.FUCA, ...
                "LCO",  testCase.P.FLCO, ...
                "LCF",  testCase.P.FLCF, ...
